"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const os = require("os");
const fs = require("fs");
const path = require("path");
const { openStore } = require("../../lib/store");

test("store round-trips a session, messages, steps, review states and usage", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "cc-store-"));
  const s = openStore(dir, { refPrefix: "HC" });
  const { ref, viewKey } = s.createSession({ town: "hildale", text: "hello world", sketch: { mime: "image/png", data: Buffer.from([0x89, 0x50, 0x4e, 0x47]) } });
  assert.match(ref, /^HC-\d{4}-\d{4}$/);
  assert.ok(viewKey.length >= 8);
  let app = s.getSession(ref);
  assert.equal(app.messages.length, 1);
  assert.equal(app.messages[0].role, "resident");
  assert.equal(app.steps.find((x) => x.name === "sketch").status, "pending");
  s.addMessage(ref, { role: "desk", department: "planning", character: "Juniper", text: "hi" });
  s.setStep(ref, "research", { status: "running" });
  s.setStep(ref, "research", { status: "done", output: { tool_calls: 3 } });
  s.updateSession(ref, { status: "ready", department: "planning", packet: { title: "Lot split", packet_type: "application_set", documents: [] }, parcel: { id: "HD-1" }, owner: { name: "Jane Alder", fictional: true } });
  s.saveReview(ref, { process_tier: "administrative", process_summary: "x", considerations: [{ id: "lot-area", title: "Lot area" }] }, "muse-spark-1.3");
  s.setReviewState(ref, "lot-area", { state: "met", note: "ok" });
  s.addConsideration(ref, { id: "staff-1", title: "Call the utility committee", added_by: "staff" });
  s.addStaffAction(ref, { action: "letter_saved", payload: { subject: "a", body: "b" } });
  s.logUsage({ tag: "t", model: "m", prompt_tokens: 10, completion_tokens: 5, ms: 1 });
  app = s.getSession(ref);
  assert.equal(app.status, "ready");
  assert.equal(app.messages.length, 2);
  assert.equal(app.has_sketch, true);
  assert.equal(app.view_key, viewKey);
  assert.deepEqual(app.steps.find((x) => x.name === "research").output, { tool_calls: 3 });
  assert.equal(app.review.model, "muse-spark-1.3");
  assert.equal(app.review.considerations.length, 2);
  assert.equal(app.review.states["lot-area"].state, "met");
  assert.equal(app.review.states["staff-1"].state, "not_started");
  assert.equal(app.owner.fictional, true);
  assert.equal(s.callsToday().n, 1);
  assert.equal(s.getSketch(ref).data.length, 4);
  const list = s.listSessions();
  assert.equal(list.length, 1);
  assert.equal(list[0].title, "Lot split");
  assert.equal(list[0].preview, "hello world");
  assert.throws(() => s.updateSession(ref, { status: "bogus" }));
  const second = s.createSession({ town: "hildale", text: "second" });
  assert.notEqual(second.ref, ref);
  s.close();
});
